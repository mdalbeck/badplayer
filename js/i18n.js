const DICTS = { de: DE, en: EN };
export const LANGS = ['de', 'en'];

function initial() {
  try { const l = localStorage.getItem(LS_KEY); if (DICTS[l]) return l; } catch { /* privat */ }
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
}
let cur = initial();

export const lang = () => cur;
export function setLang(l) {
  if (!DICTS[l]) return;
  cur = l;
  try { localStorage.setItem(LS_KEY, l); } catch { /* privat */ }
  document.documentElement.lang = l;
}
document.documentElement.lang = cur;

export function t(key, vars) {
  let s = DICTS[cur][key] ?? DE[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

const loc = () => (cur === 'de' ? 'de-DE' : 'en-GB');
/** Datum/Uhrzeit in der aktuellen Sprache */
export const fmtDateTime = (ts) => new Date(ts).toLocaleString(loc(), { dateStyle: 'medium', timeStyle: 'short' });
/** Tag 'JJJJ-MM-TT' anzeigen. style: 'short' (18.11.), 'wd' (Di), 'wdShort' (Fr, 21.11.), 'long' */
export function fmtDay(day, style = 'short') {
  const d = new Date(`${day}T12:00:00`);
  if (Number.isNaN(+d)) return '';
  const o = { short: { day: 'numeric', month: cur === 'de' ? 'numeric' : 'short' }, wd: { weekday: 'short' },
    wdShort: { weekday: 'short', day: 'numeric', month: cur === 'de' ? 'numeric' : 'short' }, long: { dateStyle: 'long' } }[style];
  const s = d.toLocaleDateString(loc(), o);
  return cur === 'de' && style !== 'long' && style !== 'wd' && !s.endsWith('.') ? `${s}.` : s;
}
export const monthLabel = (day) => new Date(`${day}T12:00:00`).toLocaleDateString(loc(), { month: 'long', year: 'numeric' });
